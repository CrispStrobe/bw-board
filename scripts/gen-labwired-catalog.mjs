#!/usr/bin/env node
/**
 * Generate src/labwired-catalog.js: the labwired chips a user can run their
 * OWN firmware on, as the engine itself defines them.
 *
 * Each entry is the chip's `configs/chips/<name>.yaml` at the SAME labwired
 * commit the shipped wasm is built from (build-labwired-wasm.mjs `PIN`), so the
 * chip text and the engine that parses it cannot come from different trees.
 * Every `path:` / `debug_schema:` a chip references is embedded in that wasm
 * (labwired's `embedded_descriptor_registry_is_complete` gate), which is why
 * the bare chip text is enough in a browser.
 *
 *   node scripts/gen-labwired-catalog.mjs --labwired <labwired-core checkout>
 *
 * The checkout needs the PIN commit (fetch the CrispStrobe fork). Re-run after
 * every PIN bump; test/labwired-catalog.test.mjs fails until you do.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

/** Chips offered for user firmware, in picker order. Adding one is a row here. */
export const CATALOG_CHIPS = [
  'stm32f103', 'stm32f401', 'stm32f407', 'stm32l476', 'stm32g474re',
  'nrf52832', 'nrf52833', 'nrf52840',
  'rp2040', 'rp2350',
  'atsamd21g18a', 'atsamd51', 'ra4m1',
  'esp32c3', 'esp32c6', 'esp32', 'esp32s3',
];

/**
 * Display types whose engine pixel format the labwired target decodes
 * (labwired-debug.js decodeDisplay): page-packed monochrome and RGB565.
 * A board whose only display is something else (e-paper, 7-segment, text) is
 * left out rather than offered with a blank screen.
 */
export const DECODABLE_DISPLAY = /(ssd1306|sh1107|pcd8544|ili9341|st7789|st7735)/i;

/** `external_devices` rows of a system manifest: [{id, type}]. Strict and flat, like the files. */
export function externalDevices(systemYaml) {
  const out = [];
  const body = systemYaml.split(/^external_devices:\s*$/m)[1];
  if (!body) return out;
  const block = body.split(/^\S/m)[0];                       // up to the next top-level key
  for (const m of block.matchAll(/^\s+-\s+id:\s*"?([A-Za-z0-9_-]+)"?\s*\n\s+type:\s*"?([A-Za-z0-9_-]+)"?/gm)) {
    out.push({ id: m[1], type: m[2] });
  }
  return out;
}

export function buildScriptPin() {
  const text = readFileSync(join(root, 'scripts/build-labwired-wasm.mjs'), 'utf8');
  const m = text.match(/^const PIN = '([0-9a-f]{40})';$/m);
  if (!m) throw new Error('build-labwired-wasm.mjs has no `const PIN = \'<40 hex>\';` line');
  return m[1];
}

function main() {
  const at = process.argv.indexOf('--labwired');
  if (at < 0 || !process.argv[at + 1]) {
    console.error('usage: gen-labwired-catalog.mjs --labwired <labwired-core checkout>');
    process.exit(2);
  }
  const dir = process.argv[at + 1];
  const pin = buildScriptPin();
  const entries = CATALOG_CHIPS.map((name) => {
    const yaml = execFileSync('git', ['-C', dir, 'show', `${pin}:configs/chips/${name}.yaml`],
      { encoding: 'utf8' });
    const arch = (yaml.match(/^arch:\s*"?([a-z0-9-]+)"?\s*$/m) || [])[1];
    const hz = (yaml.match(/^cpu_hz:\s*([0-9_]+)\s*$/m) || [])[1];
    if (!arch || !hz) throw new Error(`${name}: chip YAML has no top-level arch/cpu_hz`);
    return { name, arch, clockHz: Number(hz.replace(/_/g, '')), yaml };
  });
  const systems = execFileSync('git', ['-C', dir, 'ls-tree', '--name-only', `${pin}:configs/systems/`],
    { encoding: 'utf8' }).split('\n').filter(n => n.endsWith('.yaml')).sort();
  const boards = [];
  for (const file of systems) {
    const yaml = execFileSync('git', ['-C', dir, 'show', `${pin}:configs/systems/${file}`], { encoding: 'utf8' });
    const chip = (yaml.match(/^chip:\s*"?\.\.\/chips\/([a-z0-9-]+)\.yaml"?\s*$/m) || [])[1];
    if (!chip || !CATALOG_CHIPS.includes(chip)) continue;
    const displays = externalDevices(yaml).filter(d => DECODABLE_DISPLAY.test(d.type));
    if (!displays.length) continue;
    boards.push({ name: file.replace(/\.yaml$/, ''), chip, displays, systemYaml: yaml });
  }
  const out = [
    '// GENERATED by scripts/gen-labwired-catalog.mjs -- do not edit.',
    `// Source: labwired-core ${pin} configs/chips/*.yaml (the wasm build PIN).`,
    '/**',
    ' * Chips the labwired tier can run a user-supplied firmware image on, with',
    ' * the engine\'s own chip descriptor for each. See the generator header.',
    ' * @module',
    ' */',
    '',
    `export const LABWIRED_CATALOG_PIN = '${pin}';`,
    '',
    '/** name -> { name, arch, clockHz, chipYaml } in picker order. */',
    'export const LABWIRED_CATALOG = Object.freeze({',
    ...entries.map(e => `  ${JSON.stringify(e.name)}: Object.freeze({ name: ${JSON.stringify(e.name)}, ` +
      `arch: ${JSON.stringify(e.arch)}, clockHz: ${e.clockHz}, chipYaml: ${JSON.stringify(e.yaml)} }),`),
    '});',
    '',
    '/**',
    ' * Labwired boards (configs/systems/*.yaml at the same PIN) on a catalog chip',
    ' * that carry a display this tier can draw: name -> { name, chip, displays',
    ' * [{id, type}], systemYaml }. Picking one runs the user\'s firmware with that',
    ' * board\'s devices attached, so what the firmware draws reaches the screen.',
    ' */',
    'export const LABWIRED_BOARDS = Object.freeze({',
    ...boards.map(b => `  ${JSON.stringify(b.name)}: Object.freeze({ name: ${JSON.stringify(b.name)}, ` +
      `chip: ${JSON.stringify(b.chip)}, displays: ${JSON.stringify(b.displays)}, systemYaml: ${JSON.stringify(b.systemYaml)} }),`),
    '});',
    '',
    'export default LABWIRED_CATALOG;',
    '',
  ].join('\n');
  writeFileSync(join(root, 'src/labwired-catalog.js'), out);
  console.log(`wrote src/labwired-catalog.js: ${entries.length} chips, ${boards.length} display boards at ${pin}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
