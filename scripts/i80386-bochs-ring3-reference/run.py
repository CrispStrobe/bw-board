def normal_manager_delivery(process):
    """A retained normal nonzero diagnostic exit is data, not an unknown exit.

    child_capture's ordinary exit0 assertion remains unchanged. Only its exact
    source-generated nonzero-status refusal is permitted here; caps, signals,
    missing reap, timeouts, callback/close failures remain delivery failures.
    """
    status = process.get('waitStatus')
    code = process.get('exitCode')
    if not (type(status) is int and type(code) is int and 0 <= code <= 255 and
            os.WIFEXITED(status) and os.WEXITSTATUS(status) == code and
            process.get('reaped') is True and process.get('timedOut') is False and
            process.get('signal') is None and process.get('secondary') == [] and
            process.get('stdout', {}).get('complete') is True and
            process.get('stderr', {}).get('complete') is True):
        return False
    expected = None if code == 0 else failure(Refusal('ordinary child completed exit0'), 'child-capture')
    return process.get('firstFailure') == expected


