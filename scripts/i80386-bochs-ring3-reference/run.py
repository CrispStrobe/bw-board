def cleanup_node_stage(route, env, inner):
    """Remove only the exact source-created stage, with a bounded raw journal.

    Unknown names/identity stop before mutation. Partial staging without retained
    file identity remains an honest cleanup refusal, never guessed ownership.
    """
    paths = route_paths(route, env)
    root = paths['node']
    value = {'schema': 'bw.bochs-ring3.node-cleanup.v1', 'route': route,
        'path': str(root), 'parentBefore': None, 'parentAfter': None,
        'before': None, 'members': {}, 'journal': [], 'after': None,
        'complete': False, 'firstFailure': None, 'secondary': []}
    directory_fd = None
    def issue(exc, phase):
        row = failure(exc, phase, path=str(root))
        if value['firstFailure'] is None:
            value['firstFailure'] = row
        elif len(value['secondary']) < SECONDARY_LIMIT:
            value['secondary'].append(row)
    def first_five(row):
        return tuple(row[k] for k in ('dev', 'ino', 'mode', 'uid', 'gid'))
    def meta_row(raw):
        need(type(raw) is list and len(raw) == 9, 'retained staged identity before cleanup')
        return dict(zip(('dev', 'ino', 'mode', 'uid', 'gid', 'nlink', 'size', 'mtimeNs', 'ctimeNs'), raw))
    def absent(path):
        try:
            observed = os.lstat(path)
        except FileNotFoundError as exc:
            need(exc.errno == 2, 'actual ENOENT terminal stage observation')
            return {'exists': False, 'errno': 2, 'identity': None}
        return {'exists': True, 'errno': None, 'identity': identity(observed)}
    def mutation(operation, path, before, action):
        row = {'operation': operation, 'path': str(path), 'before': before,
               'attempted': False, 'after': None, 'firstFailure': None}
        value['journal'].append(row)
        need(len(canonical(value)) <= 16384, 'actual Node cleanup budget before mutation')
        row['attempted'] = True
        try:
            action()
            row['after'] = absent(path)
        except BaseException as exc:
            row['firstFailure'] = failure(exc, 'node-cleanup-' + operation, path=str(path))
            try:
                row['after'] = absent(path)
            except BaseException as extra:
                issue(extra, 'node-cleanup-failed-after')
            raise
    try:
        value['parentBefore'] = safe_root_directory('/run')
        facts = None if inner is None else (inner.get('observations') or {}).get('nodeStage')
        if facts is None and inner is not None and type(inner.get('failurePartial')) is dict:
            facts = inner['failurePartial'].get('nodeStage')
        value['before'] = absent(root)
        if not value['before']['exists']:
            need(facts is None or str(root) not in facts.get('created', []),
                 'created staged root may not disappear before owned cleanup')
            value['after'] = value['before']
        else:
            need(type(facts) is dict and facts.get('stagePath') == str(root / 'node') and
                 str(root) in facts.get('created', []), 'bound source-created Node root')
            expected_directory = facts.get('directory') or facts.get('directoryAfterFailure') or facts.get('directoryInitial')
            expected_directory = meta_row(expected_directory)
            need(first_five(value['before']['identity']) == first_five(expected_directory),
                 'exact first-five staged directory before cleanup')
            directory_fd = os.open(root, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
            need(first_five(identity(os.fstat(directory_fd))) == first_five(expected_directory),
                 'held Node cleanup directory identity')
            names = []
            with os.scandir(root) as entries:
                for entry in entries:
                    names.append(entry.name)
                    need(len(names) <= 2 and entry.name in ('node', 'stage.json'),
                         'no unknown staged Node member')
            expected = {}
            if 'node' in names:
                expected['node'] = meta_row(facts.get('file') or facts.get('targetAfterFailure') or
                                            facts.get('fileBeforePublication') or facts.get('fileInitial'))
            if 'stage.json' in names:
                need(type(facts.get('record')) is dict, 'retained installation-record identity')
                expected['stage.json'] = meta_row(facts['record']['metadata'])
            for name in names:
                observed = identity(os.stat(name, dir_fd=directory_fd, follow_symlinks=False))
                need(stat.S_ISREG(observed['mode']) and observed['uid'] == observed['gid'] == 0 and
                     observed['nlink'] == 1 and first_five(observed) == first_five(expected[name]),
                     'exact owned staged member before any cleanup mutation')
                value['members'][name] = observed
            mutation('chmod-private', root, value['before']['identity'],
                     lambda: os.fchmod(directory_fd, 0o700))
            private = identity(os.fstat(directory_fd))
            need(private['mode'] == stat.S_IFDIR | 0o700 and
                 (private['dev'], private['ino'], private['uid'], private['gid']) ==
                 tuple(expected_directory[k] for k in ('dev', 'ino', 'uid', 'gid')),
                 'same privately writable cleanup root')
            for name in sorted(names):
                observed = identity(os.stat(name, dir_fd=directory_fd, follow_symlinks=False))
                need(first_five(observed) == first_five(expected[name]) and
                     first_five(identity(os.fstat(directory_fd))) == first_five(private) and
                     first_five(identity(os.lstat(root))) == first_five(private),
                     'held/named identities before each staged unlink')
                mutation('unlink', root / name, observed,
                         lambda name=name: os.unlink(name, dir_fd=directory_fd))
            with os.scandir(root) as entries:
                need(next(entries, None) is None, 'empty known staged root before rmdir')
            need(first_five(identity(os.lstat(root))) == first_five(private) and
                 first_five(identity(os.fstat(directory_fd))) == first_five(private),
                 'held/named root before final rmdir')
            mutation('rmdir', root, private, lambda: os.rmdir(root))
            value['after'] = absent(root)
            need(value['after']['exists'] is False, 'owned Node root absent after cleanup')
        value['parentAfter'] = safe_root_directory('/run')
        need(first_five(value['parentBefore']) == first_five(value['parentAfter']),
             'fixed root parent first-five after Node cleanup')
    except BaseException as exc:
        issue(exc, 'node-stage-cleanup')
    finally:
        if directory_fd is not None:
            try:
                os.close(directory_fd)
            except BaseException as exc:
                issue(exc, 'node-cleanup-directory-close')
    value['complete'] = value['firstFailure'] is None and not value['secondary']
    return value




def source_http(url, cap, *, minimum=1, token=None):
    """One bounded data GET; no acquired bytes execute before their role joins.

    Caller supplies only source-constructed upstream or owned-artifact URLs.
    Redirect credentials are stripped, signed redirect URLs never retained.
    SIGALRM bounds a blocked network read, not just checks between reads.
    """
    need(type(url) is str and url.startswith('https://') and
         (url.startswith('https://raw.githubusercontent.com/' + UPSTREAM + '/' + UPSTREAM_COMMIT + '/') or
          url == VGA_SOURCE_URL or
          url.startswith('https://api.github.com/repos/' + UPSTREAM + '/git/trees/' + UPSTREAM_TREE + '?') or
          url.startswith('https://api.github.com/repos/' + REPOSITORY + '/actions/')),
         'source-fixed HTTPS data route')
    integer(cap, 1, 67108864, 'bounded data GET cap')
    need(0 <= minimum <= cap, 'typed empty/nonempty data extent')
    class Redirect(urllib.request.HTTPRedirectHandler):
        count = 0
        def redirect_request(self, req, fp, code, msg, headers, newurl):
            self.count += 1
            need(self.count <= 3 and newurl.startswith('https://'), 'bounded HTTPS redirect transport')
            redirected = super().redirect_request(req, fp, code, msg, headers, newurl)
            if redirected is not None:
                redirected.remove_header('Authorization')
            return redirected
    def alarm(_number, _frame):
        raise TimeoutError('bounded data GET wall deadline')
    old_alarm = signal.getsignal(signal.SIGALRM)
    previous = signal.getitimer(signal.ITIMER_REAL)
    need(previous == (0.0, 0.0), 'no preexisting network deadline owner')
    response = None
    raw = bytearray()
    primary = None
    secondary = []
    started = time.monotonic_ns()
    try:
        signal.signal(signal.SIGALRM, alarm)
        signal.setitimer(signal.ITIMER_REAL, 45)
        headers = {'User-Agent': 'bw-bochs-source-v1', 'Accept': 'application/vnd.github+json'}
        if token is not None:
            need(type(token) is str and 1 <= len(token) <= 4096 and '\0' not in token,
                 'trusted owned-artifact token shape')
            headers['Authorization'] = 'Bearer ' + token
        request = urllib.request.Request(url, headers=headers, method='GET')
        response = urllib.request.build_opener(Redirect()).open(request, timeout=45)
        need(response.status == 200, 'one admitted data GET HTTP200')
        length = response.headers.get('Content-Length')
        if length is not None:
            need(re.fullmatch(r'0|[1-9][0-9]*', length) and minimum <= int(length) <= cap,
                 'bounded official data Content-Length')
        while True:
            part = response.read(min(65536, cap + 1 - len(raw)))
            if not part:
                break
            raw.extend(part)
            need(len(raw) <= cap, 'one data GET stream cap')
        need(minimum <= len(raw) <= cap and (length is None or int(length) == len(raw)),
             'complete role-typed data response')
        need(time.monotonic_ns() - started <= 45000000000, 'actual bounded data wall extent')
    except BaseException as exc:
        primary = exc
    finally:
        if response is not None:
            try:
                response.close()
            except BaseException as exc:
                if primary is None:
                    primary = exc
                else:
                    secondary.append(failure(Refusal(type(exc).__name__), 'data-response-close'))
        try:
            signal.setitimer(signal.ITIMER_REAL, 0)
            signal.signal(signal.SIGALRM, old_alarm)
        except BaseException as exc:
            if primary is None:
                primary = exc
            else:
                secondary.append(failure(Refusal(type(exc).__name__), 'data-alarm-close'))
    if primary is not None:
        # Exceptions from urllib can include signed redirect URLs; keep only a
        # source-owned phase/reason here, never its repr or response body.
        error = Refusal('bounded source/owned-artifact GET failed: ' + type(primary).__name__)
        error.bochs_partial = {'bytes': len(raw), 'sha256': sha256(raw),
                               'complete': False, 'secondary': secondary}
        raise error from None
    return bytes(raw)


def source_archive(files, modes):
    output = io.BytesIO()
    with tarfile.open(fileobj=output, mode='w', format=tarfile.USTAR_FORMAT) as archive:
        for name, raw in sorted(files.items()):
            member_name(name)
            item = tarfile.TarInfo(name)
            item.uid = item.gid = item.mtime = 0
            item.mode = modes[name]
            item.size = len(raw)
            archive.addfile(item, io.BytesIO(raw))
    return gzip.compress(output.getvalue(), compresslevel=6, mtime=0)


def caller_directory(path, uid, gid):
    os.mkdir(path, 0o700)
    fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
    primary = None
    try:
        os.fchmod(fd, 0o755)
        os.fchown(fd, uid, gid)
        row = identity(os.fstat(fd))
        need(row['uid'] == uid and row['gid'] == gid and row['mode'] == stat.S_IFDIR | 0o755 and
             row == identity(os.lstat(path)), 'new exact invoker-owned source directory')
    except BaseException as exc:
        primary = exc
    finally:
        try:
            os.close(fd)
        except BaseException as exc:
            if primary is None:
                primary = exc
            else:
                primary.bochs_secondary = [failure(exc, 'source-directory-close')]
    if primary is not None:
        raise primary


def caller_file(path, raw, mode, uid, gid):
    retain_exclusive(path, raw, 67108864)
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
    primary = None
    try:
        before = identity(os.fstat(fd))
        need(before['uid'] == before['gid'] == 0 and stat.S_ISREG(before['mode']) and
             before['nlink'] == 1 and before['size'] == len(raw), 'new owned raw input before publication')
        os.fchmod(fd, mode)
        os.fchown(fd, uid, gid)
        after = identity(os.fstat(fd))
        need(after['uid'] == uid and after['gid'] == gid and
             after['mode'] == stat.S_IFREG | mode and after == identity(os.lstat(path)) and
             (after['dev'], after['ino']) == (before['dev'], before['ino']),
             'new exact invoker-owned source file')
    except BaseException as exc:
        primary = exc
    finally:
        try:
            os.close(fd)
        except BaseException as exc:
            if primary is None:
                primary = exc
            else:
                primary.bochs_secondary = [failure(exc, 'source-input-close')]
    if primary is not None:
        raise primary



def cleanup_owned_cgroups(route, env, inner, kernel, *, clock=time.monotonic_ns, sleep=time.sleep):
    """Known delegated roles only; no kill, retry, arbitrary path or unknown rmdir."""
    paths = route_paths(route, env)
    root = Path('/sys/fs/cgroup/system.slice') / paths['unit']
    allowed = {'controller'} | ({'configure', 'make'} if route == 'build' else
                                {'js', 'bochs'} if route == 'reference' else set())
    started = clock()
    last = started
    value = {'schema': 'bw.bochs-ring3.manual-cleanup.v1', 'route': route,
        'unit': paths['unit'], 'rootPath': str(root),
        'limits': {'samples': 6, 'seconds': 5, 'bytes': 16384},
        'startedNs': started, 'endedNs': None, 'known': {}, 'samples': [],
        'journal': [], 'after': None, 'firstFailure': None, 'secondary': [], 'complete': False}
    def issue(exc, phase):
        row = failure(exc, phase)
        if value['firstFailure'] is None:
            value['firstFailure'] = row
        elif len(value['secondary']) < SECONDARY_LIMIT:
            value['secondary'].append(row)
        for row in getattr(exc, 'bochs_secondary', []):
            if len(value['secondary']) < SECONDARY_LIMIT:
                value['secondary'].append(row)
    def tick():
        nonlocal last
        now = clock()
        need(now >= last and now - started < 5000000000, 'strict finite monotonic cleanup deadline')
        last = now
        return now
    def first_five(row):
        return tuple(row[k] for k in ('dev', 'ino', 'mode', 'uid', 'gid'))
    def snapshot(path):
        try:
            before = kernel._directory(path)
        except FileNotFoundError as exc:
            need(exc.errno == 2, 'actual selected cgroup ENOENT')
            return {'path': str(path), 'exists': False, 'errno': 2,
                    'identity': None, 'files': {}, 'children': []}
        files = {name: kernel._read(path / name, 4096) for name in RESOURCE_FILES}
        children = []
        with os.scandir(path) as entries:
            count = 0
            for entry in entries:
                count += 1
                need(count <= 128 and not entry.is_symlink(), 'bounded nonlink cleanup cgroup entry')
                if entry.is_dir(follow_symlinks=False):
                    children.append(entry.name)
                    need(len(children) <= len(allowed), 'bounded selected cleanup descendants')
        need(first_five(before) == first_five(kernel._directory(path)), 'stable cleanup group identity')
        return {'path': str(path), 'exists': True, 'errno': None, 'identity': before,
                'files': files, 'children': sorted(children)}
    def raw_zero(raw, key):
        lines = raw.splitlines()
        return lines.count(key + ' 0') == 1 and not any(
            line.startswith(key + ' ') and line != key + ' 0' for line in lines)
    try:
        if inner is not None and type(inner.get('resources')) is dict:
            before = inner['resources'].get('before')
            if type(before) is dict and before.get('schema') == 'bw.bochs-ring3.resources.v2':
                for role, key in (('unit', 'unitRoot'), ('controller', 'controller')):
                    row = before[key]
                    expected = root if role == 'unit' else root / role
                    need(row['path'] == str(expected), 'source-bound initial cleanup role path')
                    value['known'][role] = {'path': str(expected), 'identity': row['directory']}
            phases = inner.get('phases', [])
            if type(phases) is list:
                for process in phases:
                    role = process.get('name')
                    group = process.get('cgroupBefore')
                    if role in allowed and type(group) is dict and type(group.get('identity')) is dict:
                        need(group['path'] == str(root / role), 'source-bound child cleanup path')
                        value['known'][role] = {'path': str(root / role), 'identity': group['identity']}
        quiet = None
        for index in range(6):
            sample = {'ns': tick(), 'roles': {}}
            value['samples'].append(sample)
            top = snapshot(root)
            sample['roles']['unit'] = top
            if not top['exists']:
                value['after'] = top
                quiet = sample
                break
            need('unit' in value['known'] and first_five(top['identity']) ==
                 first_five(value['known']['unit']['identity']), 'known unit identity before cleanup')
            names = set(top['children'])
            need(names <= allowed and names <= set(value['known']), 'no unknown cgroup cleanup role')
            all_quiet = top['files']['cgroup.procs'] == ''
            for role in sorted(names):
                row = snapshot(root / role)
                sample['roles'][role] = row
                need(row['exists'] and not row['children'] and first_five(row['identity']) ==
                     first_five(value['known'][role]['identity']), 'known child identity and no nested subtree')
                all_quiet = all_quiet and row['files']['cgroup.procs'] == '' and \
                    raw_zero(row['files']['cgroup.events'], 'populated') and \
                    raw_zero(row['files']['cgroup.stat'], 'nr_descendants') and \
                    raw_zero(row['files']['cgroup.stat'], 'nr_dying_descendants')
            all_quiet = all_quiet and raw_zero(top['files']['cgroup.events'], 'populated') and \
                raw_zero(top['files']['cgroup.stat'], 'nr_dying_descendants')
            if all_quiet:
                quiet = sample
                break
            if index < 5:
                sleep(0.05)
        need(quiet is not None, 'owned cgroup terminal state remains uncertain')
        if value['after'] is None:
            top = quiet['roles']['unit']
            order = sorted(set(top['children']) - {'controller'})
            if 'controller' in top['children']:
                order.append('controller')
            order.append('unit')
            for role in order:
                tick()
                path = root if role == 'unit' else root / role
                row = snapshot(path)
                need(row['exists'] and not row['children'] and row['files']['cgroup.procs'] == '' and
                     raw_zero(row['files']['cgroup.events'], 'populated') and
                     raw_zero(row['files']['cgroup.stat'], 'nr_descendants') and
                     raw_zero(row['files']['cgroup.stat'], 'nr_dying_descendants') and
                     first_five(row['identity']) == first_five(value['known'][role]['identity']),
                     'exact empty role immediately before rmdir')
                parent_before = kernel._directory(path.parent)
                parent_fd = child_fd = None
                primary = None
                journal = {'role': role, 'path': str(path), 'before': row,
                    'parentBefore': parent_before, 'attempted': False, 'after': None,
                    'firstFailure': None}
                value['journal'].append(journal)
                try:
                    parent_fd = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
                    child_fd = os.open(path.name, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC,
                                       dir_fd=parent_fd)
                    need(first_five(identity(os.fstat(parent_fd))) == first_five(parent_before) ==
                         first_five(kernel._directory(path.parent)) and
                         first_five(identity(os.fstat(child_fd))) == first_five(row['identity']) ==
                         first_five(kernel._directory(path)), 'held per-name parent/child cleanup authority')
                    tick()
                    need(len(canonical(value)) <= 16384, 'actual top-level cleanup budget before rmdir')
                    journal['attempted'] = True
                    os.rmdir(path.name, dir_fd=parent_fd)
                    journal['after'] = snapshot(path)
                    need(journal['after']['exists'] is False, 'rmdir actual selected role absence')
                except BaseException as exc:
                    primary = exc
                    journal['firstFailure'] = failure(exc, 'owned-cgroup-rmdir')
                    try:
                        journal['after'] = snapshot(path)
                    except BaseException as extra:
                        issue(extra, 'owned-cgroup-failed-after')
                finally:
                    for fd in (child_fd, parent_fd):
                        if fd is not None:
                            try:
                                os.close(fd)
                            except BaseException as exc:
                                if primary is None:
                                    primary = exc
                                else:
                                    issue(exc, 'owned-cgroup-close-secondary')
                if primary is not None:
                    raise primary
            value['after'] = snapshot(root)
            need(value['after']['exists'] is False, 'complete selected root cgroup absent')
    except BaseException as exc:
        issue(exc, 'owned-cgroup-cleanup')
    finally:
        try:
            value['endedNs'] = tick()
        except BaseException as exc:
            value['endedNs'] = last
            issue(exc, 'owned-cgroup-terminal-clock')
    value['complete'] = value['firstFailure'] is None and not value['secondary']
    return value


RESOURCE_FILES = ('cpu.max', 'memory.max', 'memory.swap.max', 'pids.max',
                  'cgroup.procs', 'cgroup.events', 'cgroup.stat', 'cpu.stat')


class LiveOps:
    """Source-owned ordinary/kernel edges. No observed tool is a metadata probe.

    Construction does not read kernel state; admitted source/context precedes
    every call. Compiler/reference methods are connected separately below.
    """
    def __init__(self, route, context, paths):
        self.route, self.context, self.paths = route, context, paths
        self.env = context['env']
        self.invoker = context['invoker']
        self.started_ns = time.monotonic_ns()
        self.unit_path = Path('/sys/fs/cgroup/system.slice') / paths['unit']
        self.child = None
        if route in ('build', 'reference'):
            self.child = ChildProcessProvider(route, {
                'PATH': '/usr/bin:/bin', 'LANG': 'C', 'LC_ALL': 'C',
                'HOME': str(paths['work'] / 'home'), 'TMPDIR': str(paths['work'] / 'tmp')},
                self.invoker['uid'], self.invoker['gid'], paths['work'], self.unit_path)
            self.kernel = self.child.kernel
        else:
            self.kernel = ChildKernel(self.unit_path, paths['work'])
        self.stage = None
        self.last_graph = None
        self.upstream_record = None
    def source(self, selected, env):
        return observe_source(self.context['sourceRoot'], selected, env, self.context['workflowRoot'])
    def read(self, path, cap, **kwargs):
        return read_regular(path, cap, **kwargs)
    def _group(self, path):
        before = self.kernel._directory(path)
        files = {name: self.kernel._read(path / name, 4096) for name in RESOURCE_FILES}
        children = []
        with os.scandir(path) as entries:
            count = 0
            for entry in entries:
                count += 1
                need(count <= 128 and not entry.is_symlink(), 'bounded ordinary cgroup entries')
                if entry.is_dir(follow_symlinks=False):
                    children.append(entry.name)
                    need(len(children) <= 5, 'finite fixed cgroup children')
        need(self.kernel._first_five(before) == self.kernel._first_five(self.kernel._directory(path)),
             'resource cgroup directory first-five identity')
        return {'path': str(path), 'directory': before, 'files': files, 'children': sorted(children)}
    def resources(self, route):
        need(route == self.route, 'source-selected resource route')
        pid = os.getpid()
        need(os.getresuid() == os.getresgid() == (0, 0, 0), 'root service actual credentials')
        limits = LIMITS[route]
        expected = {'cpu.max': '100000 100000\n', 'memory.max': str(limits['memoryBytes']) + '\n',
                    'memory.swap.max': '0\n', 'pids.max': str(limits['tasks']) + '\n'}
        # Read the actual selected unit envelope before enabling controllers or
        # touching observed tool/cache/source inputs.
        for name, text in expected.items():
            need(self.kernel._read(self.unit_path / name, 4096) == text,
                 'actual selected finite root unit limit ' + name)
        if self.kernel.delegation is None:
            self.kernel.prepare_delegation(pid)
        parent = self.kernel.parent_control()
        root = self._group(self.unit_path)
        control = self._group(self.unit_path / 'controller')
        allowed = {'controller'} | (set() if self.child is None else self.child.used)
        need(set(root['children']) <= allowed and 'controller' in root['children'] and
             not control['children'] and root['files']['cgroup.procs'] == '' and
             control['files']['cgroup.procs'] == str(pid) + '\n', 'fixed unit/controller membership')
        need(all(root['files'][name] == text for name, text in expected.items()),
             'held actual unit resource limits')
        raw_cgroup = self.kernel._read(Path('/proc') / str(pid) / 'cgroup', 16384)
        need(raw_cgroup == '0::/system.slice/' + self.paths['unit'] + '/controller\n',
             'actual root observer controller membership')
        return {'schema': 'bw.bochs-ring3.resources.v2', 'unit': self.paths['unit'],
            'pid': pid, 'uid': os.getuid(), 'gid': os.getgid(), 'unitRoot': root, 'controller': control,
            'procCgroup': raw_cgroup,
            'procStat': self.kernel._read(Path('/proc') / str(pid) / 'stat', 16384),
            'procStatus': self.kernel._read(Path('/proc') / str(pid) / 'status', 16384),
            'parentControl': parent}
    def node_stage(self):
        need(self.stage is None, 'source-owned one Node stage')
        self.stage = NodeStageCopy(self.route, self.env, (self.invoker['uid'], self.invoker['gid']))
        return self.stage.copy()
    def node_after(self, *, full_hash):
        need(self.stage is not None, 'Node stage exists before after-readback')
        return self.stage.verify_after(full_hash=full_hash)
    def toolchain(self):
        need(self.stage is not None and self.stage.facts['elf'] is not None,
             'verified staged Node before selected tool data inventory')
        self.last_graph = observe_toolchain(node_elf=self.stage.facts['elf'])
        return self.last_graph
    def notices(self):
        need(self.last_graph is not None, 'notice identities selected by current tool graph')
        result = {}
        for source_path in NOTICE_PATHS:
            aliases, directories = {}, {}
            path = resolve_tool(source_path, aliases, directories)
            raw, _record = read_regular(path, 262144, minimum=1)
            selected = self.last_graph['files'].get(path)
            need(selected is not None and selected['bytes'] == len(raw) and selected['sha256'] == sha256(raw),
                 'notice raw bytes equal observed selected graph')
            result[source_path] = (path, raw)
        return result
    def observer(self, value):
        return observer_facts(value, self.env, pid=os.getpid(), uid=os.getuid(), gid=os.getgid(),
                              started_ns=self.started_ns, ended_ns=time.monotonic_ns())
    def _selected_upstream_readback(self):
        result = {}
        for row in self.selected_rows['rows']:
            if not row['included']:
                continue
            path = self.paths['work'] / 'selected-source' / row['path']
            raw, observed = read_regular(path, 16777216, minimum=0,
                owner=self.invoker['uid'], group=self.invoker['gid'])
            need(len(raw) == row['bytes'] and
                 hashlib.sha1(b'blob ' + str(len(raw)).encode() + b'\0' + raw).hexdigest() == row['gitBlob'] and
                 stat.S_IMODE(observed['before']['mode']) == int(row['mode'], 8) & 0o777,
                 'current selected upstream Git/data readback ' + row['path'])
            result[row['path']] = {'mode': row['mode'], 'gitBlob': row['gitBlob'],
                'bytes': len(raw), 'sha256': sha256(raw), 'observation': observed}
        return {'schema': 'bw.bochs-ring3.upstream-source.v1', 'repository': UPSTREAM,
            'commit': UPSTREAM_COMMIT, 'tree': UPSTREAM_TREE,
            'sourceSelectionSha256': SOURCE_SELECTION_SHA256, 'files': result}
    def upstream(self, selected):
        need(self.upstream_record is None, 'selected source acquisition once')
        # A source-owned durable marker precedes every source payload acquisition.
        sealed_write(self.paths['work'] / 'source-attempt.original.json', canonical({
            'schema': 'bw.bochs-ring3.source-attempt.v1', 'commit': UPSTREAM_COMMIT,
            'tree': UPSTREAM_TREE, 'selectionSha256': SOURCE_SELECTION_SHA256}), 4096)
        tree_raw = source_http('https://api.github.com/repos/' + UPSTREAM + '/git/trees/' +
                               UPSTREAM_TREE + '?recursive=1', 4194304)
        tree = raw_object(tree_raw, 4194304)
        self.selected_rows = selected_source_rows(tree)
        root = self.paths['work'] / 'selected-source'
        caller_directory(root, self.invoker['uid'], self.invoker['gid'])
        directories = {root}
        files, modes = {}, {}
        aggregate = 0
        for row in self.selected_rows['rows']:
            if not row['included']:
                continue  # No payload request or extraction for excluded firmware/tools.
            raw = source_http('https://raw.githubusercontent.com/' + UPSTREAM + '/' +
                              UPSTREAM_COMMIT + '/' + row['path'], 16777216, minimum=0)
            aggregate += len(raw)
            need(aggregate <= 33554432 and len(raw) == row['bytes'] and
                 hashlib.sha1(b'blob ' + str(len(raw)).encode() + b'\0' + raw).hexdigest() == row['gitBlob'],
                 'exact included Git blob bytes ' + row['path'])
            target = root / row['path']
            for parent in reversed(target.parents):
                if parent == root or root in parent.parents:
                    if parent not in directories:
                        caller_directory(parent, self.invoker['uid'], self.invoker['gid'])
                        directories.add(parent)
            mode = int(row['mode'], 8) & 0o777
            caller_file(target, raw, mode, self.invoker['uid'], self.invoker['gid'])
            files[row['path']], modes[row['path']] = raw, mode
        need(len(files[VGA_PATH]) == VGA_BYTES and sha256(files[VGA_PATH]) == VGA_SHA256,
             'selected LGPL VGA bytes equal corresponding-source reviewed resource')
        source_raw = source_http(VGA_SOURCE_URL, VGA_SOURCE_BYTES)
        need(len(source_raw) == VGA_SOURCE_BYTES and sha256(source_raw) == VGA_SOURCE_SHA256,
             'exact reviewed complete corresponding-source archive')
        selected_vga = copying = None
        with tarfile.open(fileobj=io.BytesIO(source_raw), mode='r:gz') as archive:
            members = archive.getmembers()
            need(len(members) == 31 and sum(x.size for x in members) <= 1048576 and
                 all(x.isdir() or x.isreg() for x in members) and
                 len({x.name for x in members}) == len(members), 'bounded reviewed source TAR census')
            for member in members:
                member_name(member.name.rstrip('/'))
                if member.name in ('vgabios-0.8a/VGABIOS-lgpl-latest.bin', 'vgabios-0.8a/COPYING'):
                    handle = archive.extractfile(member)
                    need(handle is not None, 'selected corresponding-source regular member')
                    try:
                        data = handle.read(1048577)
                    finally:
                        handle.close()
                    need(len(data) == member.size <= 1048576, 'bounded complete selected source member')
                    if member.name.endswith('/COPYING'):
                        copying = data
                    else:
                        selected_vga = data
        need(selected_vga == files[VGA_PATH] and copying is not None and
             sha256(copying) == VGA_LICENSE_SHA256, 'exact source correspondence and retained LGPL notice')
        archive_raw = source_archive(files, modes)
        before = self._selected_upstream_readback()
        self.upstream_record = {'tree': tree, 'before': before,
            'correspondingSource': selected['vga']['correspondingSource'],
            'sourceArchive': archive_raw, 'correspondingSourceRaw': source_raw}
        self.upstream_payloads = files
        return self.upstream_record
    def upstream_after(self):
        need(self.upstream_record is not None, 'acquired source before final readback')
        return self._selected_upstream_readback()
    def generated_headers(self):
        root = self.paths['work'] / 'selected-source' / 'bochs'
        config = read_regular(root / 'config.h', 1048576, minimum=1,
            owner=self.invoker['uid'], group=self.invoker['gid'])[0]
        version = read_regular(root / 'bxversion.h', 16384, minimum=1,
            owner=self.invoker['uid'], group=self.invoker['gid'])[0]
        return config, version
    def process(self, name, argv, **kwargs):
        need(self.child is not None, 'no observed executable in toolchain metadata')
        return self.child.process(name, argv, **kwargs)
    def unit(self, unit):
        need(unit == self.paths['unit'], 'fixed owned outside unit')
        try:
            row = self.kernel._directory(self.unit_path)
        except FileNotFoundError as exc:
            need(exc.errno == 2, 'actual absent selected unit')
            return {'path': str(self.unit_path), 'exists': False, 'errno': 2,
                    'identity': None, 'files': {}, 'children': []}
        facts = self._group(self.unit_path)
        return {'path': str(self.unit_path), 'exists': True, 'errno': None,
                'identity': row, 'files': facts['files'], 'children': facts['children']}
    def cleanup(self, inner=None):
        return cleanup_owned_cgroups(self.route, self.env, inner, self.kernel)
    def node_cleanup(self, inner):
        return cleanup_node_stage(self.route, self.env, inner)
    def close(self):
        if self.stage is not None:
            self.stage.close()
            if self.stage.facts['firstFailure'] is not None:
                error = Refusal(self.stage.facts['firstFailure']['message'])
                error.bochs_first = self.stage.facts['firstFailure']
                error.bochs_secondary = self.stage.facts['secondary']
                error.bochs_partial = {'nodeStage': self.stage.facts}
                raise error


def parse_exit(text):
    if text == 'unknown':
        return None
    need(re.fullmatch(r'0|[1-9][0-9]{0,2}', text), 'canonical retained exit argument')
    value = int(text)
    integer(value, 0, 255, 'bounded retained exit argument')
    return value


def main(argv=None, *, environment=None, provider_factory=None):
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    for flag in ('admit', 'work', 'run-service', 'capture-service-status', 'finish'):
        modes.add_argument('--' + flag, action='store_true')
    parser.add_argument('--route', choices=tuple(ROUTES), required=True)
    parser.add_argument('--workflow-root')
    parser.add_argument('--invoker-uid', type=int)
    parser.add_argument('--invoker-gid', type=int)
    parser.add_argument('--service-exit', default='unknown')
    parser.add_argument('--client-exit', default='unknown')
    parser.add_argument('--service-status')
    args = parser.parse_args(argv)
    route_enabled(args.route)  # all modes fail before env/file/kernel edges when false
    env = os.environ if environment is None else environment
    if args.admit:
        need(args.workflow_root is not None and args.invoker_uid is not None and
             args.invoker_gid is not None, 'explicit trusted workflow bootstrap arguments')
        admit_cli(args.route, env, args.workflow_root, args.invoker_uid, args.invoker_gid)
        return 0
    context, request_raw, event_raw, paths = load_cli_context(args.route, env)
    if args.run_service:
        process = run_service_cli(args.route, context, paths,
                                  secret=env.get('GH_TOKEN') if args.route == 'reference' else None)
        return 0 if process['firstFailure'] is None and not process['secondary'] and \
            process['reaped'] and process['exitCode'] == 0 else 1
    if args.capture_service_status:
        status = capture_service_status_cli(args.route, context, paths)
        return 0 if status['firstFailure'] is None and not status['secondary'] else 1
    factory = provider_factory if provider_factory is not None else LiveOps
    if args.work:
        value = work_cli(args.route, context, request_raw, event_raw, paths, provider_factory=factory)
        return 0 if value['complete'] else 1
    need(args.service_status is not None, 'explicit protected service status path')
    outside, roles = finish_cli(args.route, context, request_raw, event_raw, paths,
        provider_factory=factory, service_status=args.service_status,
        claimed_service=parse_exit(args.service_exit), claimed_client=parse_exit(args.client_exit))
    if outside['cleanupExitCode'] == 0 and args.route == 'build':
        compact = raw_object(roles['compact-manifest.json'], 32768)
        print(COMPACT_MARKER + base64.b64encode(canonical(compact)).decode('ascii'), flush=True)
    return outside['cleanupExitCode']


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except Exception as exc:
        # No context/env dump, exception args repr or traceback at the secret edge.
        print(type(exc).__name__ + ': ' + str(exc)[:ERROR_LIMIT], file=sys.stderr)
        raise SystemExit(1)
