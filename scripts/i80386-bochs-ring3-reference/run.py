def public_context_environment(route, env):
    prefix = ROUTES[route][2]
    names = CONTEXT_ENV + (prefix + '_SHA256', prefix + '_B64')
    value = {}
    for name in names:
        item = env.get(name)
        need(type(item) is str and 1 <= len(item.encode('utf-8')) <=
             (49152 if name.endswith('_B64') else 4096) and '\0' not in item,
             'bounded required context field ' + name)
        value[name] = item
