def retained_output_roles(paths, route):
    """Finite root-only tree walk; never follow a link or repair missing files."""
    limits = LIMITS[route]
    result = {}
    total = 0
    visited = 0
    def visit(directory, prefix):
        nonlocal total, visited
        safe_root_directory(directory, mode=0o755)
        with os.scandir(directory) as entries:
            for item in entries:
                visited += 1
                need(visited <= limits['members'], 'retained files and directory census cap')
                name = prefix + item.name
                member_name(name)
                need(len(result) < limits['members'], 'retained partial member cap')
                info = item.stat(follow_symlinks=False)
                if stat.S_ISDIR(info.st_mode):
                    # Depth and finite path grammar bound even an empty-dir tree.
                    need(len(Path(name).parts) <= 8, 'retained role directory depth')
                    visit(Path(directory) / item.name, name + '/')
                else:
                    raw, _fact = read_regular(Path(directory) / item.name,
                        min(limits['expandedBytes'] - total, limits['expandedBytes']), minimum=0)
                    total += len(raw)
                    need(total <= limits['expandedBytes'], 'retained partial aggregate extent')
                    result[name] = raw
    visit(paths['output'], '')
    return result


