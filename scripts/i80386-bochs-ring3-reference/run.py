def safe_root_directory(path, *, mode=None):
    """Exact non-link root directory; check every existing component."""
    path = Path(path)
    need(path.is_absolute() and '..' not in path.parts, 'absolute source-owned directory')
    for parent in (*reversed(path.parents), path):
        current = os.lstat(parent)
        need(stat.S_ISDIR(current.st_mode) and current.st_uid == current.st_gid == 0 and
             current.st_mode & 0o022 == 0, 'held safe root directory component')
    current = os.lstat(path)
    if mode is not None:
        need(stat.S_IMODE(current.st_mode) == mode, 'exact root directory mode')
    return identity(current)


def sealed_write(path, raw, cap):
    """New root-owned data only; no overwrite/retry of partial originals."""
    safe_root_directory(Path(path).parent)
    retain_exclusive(path, raw, cap)
    publish_root_mode(path, 0o444)
    check, _facts = read_regular(path, cap, minimum=0)
    need(check == raw, 'exact newly sealed retained original')


def publish_root_mode(path, mode, *, directory=False):
    """Publish only through a held no-follow root FD, never pathname chmod."""
    fd = None
    primary = None
    try:
        fd = os.open(os.fspath(path), os.O_RDONLY | os.O_CLOEXEC | os.O_NOFOLLOW |
                     (os.O_DIRECTORY if directory else 0))
        before = os.fstat(fd)
        need(before.st_uid == before.st_gid == 0 and
             (stat.S_ISDIR(before.st_mode) if directory else
              stat.S_ISREG(before.st_mode) and before.st_nlink == 1), 'owned mode publication FD')
        os.fchmod(fd, mode)
        after, named = os.fstat(fd), os.lstat(path)
        need(identity(after) == identity(named) and before.st_dev == after.st_dev and
             before.st_ino == after.st_ino and stat.S_IMODE(after.st_mode) == mode,
             'held and named exact published root mode')
    except BaseException as exc:
        primary = exc
    finally:
        if fd is not None:
            try:
                os.close(fd)
            except BaseException as exc:
                if primary is None:
                    primary = exc
                else:
                    primary.bochs_secondary = [failure(exc, 'publish-mode-close')]
    if primary is not None:
        raise primary


def admit_cli(route, env, workflow_root, invoker_uid, invoker_gid):
    route_enabled(route)  # before environment reads, paths or factories
    integer(invoker_uid, 1, 65534, 'trusted workflow invoker UID')
    integer(invoker_gid, 1, 65534, 'trusted workflow invoker GID')
    need(os.geteuid() == os.getuid() == os.getgid() == os.getegid() == 0,
         'source-owned root admission')
    need(env.get('SUDO_UID') == str(invoker_uid) and env.get('SUDO_GID') == str(invoker_gid),
         'workflow IDs joined to trusted sudo invoker')
    public = public_context_environment(route, env)
    prefix = ROUTES[route][2]
    encoded = public[prefix + '_B64']
    need(len(encoded) <= 4 * ((REQUEST_CAP + 2) // 3), 'bounded request before B64 decode')
    request_raw = base64.b64decode(encoded, validate=True)
    event_raw, _fact = read_regular(public['GITHUB_EVENT_PATH'], EVENT_CAP, minimum=1,
                                    owner=invoker_uid, group=invoker_gid)
    request = admitted_request(route, request_raw, event_raw, public)
    source_root = Path(public['GITHUB_WORKSPACE']) / 'producer-source'
    workflow_root = Path(workflow_root)
    need(workflow_root == Path(public['GITHUB_WORKSPACE']) / 'workflow-source',
         'fixed data-only executing workflow checkout')
    for checkout in (source_root, workflow_root):
        info = os.lstat(checkout)
        need(stat.S_ISDIR(info.st_mode) and info.st_uid == invoker_uid and
             info.st_gid == invoker_gid and info.st_mode & 0o022 == 0,
             'trusted invoker owns checked source directory')
    observed = observe_source(source_root, request['source'], public, workflow_root)
    paths = route_paths(route, public)
    safe_root_directory('/run')
    # Creating either directory twice refuses; do not remove a preceding attempt.
    os.mkdir(paths['work'], 0o755)
    publish_root_mode(paths['work'], 0o755, directory=True)
    safe_root_directory(paths['work'], mode=0o755)
    os.mkdir(paths['output'], 0o755)
    publish_root_mode(paths['output'], 0o755, directory=True)
    safe_root_directory(paths['output'], mode=0o755)
    context = {'schema': 'bw.bochs-ring3.protected-context.v1', 'route': route,
        'env': public, 'invoker': {'uid': invoker_uid, 'gid': invoker_gid},
        'sourceRoot': str(source_root), 'workflowRoot': str(workflow_root),
        'source': observed, 'requestSha256': sha256(request_raw), 'eventSha256': sha256(event_raw)}
    retain_exclusive(paths['work'] / 'context.original.json', canonical(context), 131072)
    sealed_write(paths['output'] / 'request.original.json', request_raw, REQUEST_CAP)
    sealed_write(paths['output'] / 'event.original.json', event_raw, EVENT_CAP)
    return context


