import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = join(root, 'rom/kim1');
const generatedPath = join(root, 'src/kim1-rom.generated.js');
const args = process.argv.slice(2);
const check = args[0] === '--check';
const binaryOutput = args[0] === '--bin-dir' && args[1] ? resolve(args[1]) : null;
if (args.length && !(check && args.length === 1) && !(binaryOutput && args.length === 2)) {
  throw new Error('Usage: node scripts/build-kim1-rom.mjs [--check | --bin-dir <directory>]');
}

const temp = mkdtempSync(join(tmpdir(), 'brickwright-kim1-rom-'));
try {
  const object = join(temp, 'monitor.o');
  const image = join(temp, 'monitor.bin');
  execFileSync('ca65', ['--cpu', '6502', join(source, 'monitor.s'), '-o', object], {stdio: 'inherit'});
  execFileSync('ld65', ['-C', join(source, 'monitor.cfg'), object, '-o', image], {stdio: 'inherit'});
  const bytes = readFileSync(image);
  if (bytes.length !== 2048) throw new Error(`Expected 2,048 ROM bytes, got ${bytes.length}.`);
  const sha256 = createHash('sha256').update(bytes).digest('hex');
  const base64 = bytes.toString('base64').match(/.{1,96}/g);
  const generated = [
    '// SPDX-License-Identifier: MIT',
    '// Generated by scripts/build-kim1-rom.mjs from rom/kim1/monitor.s.',
    `export const KIM1_ROM_SHA256 = '${sha256}';`,
    'const image = [',
    ...base64.map(chunk => `  '${chunk}',`),
    '].join(\'\');',
    '',
    'export function createBrickwrightKim1Roms() {',
    '  const bytes = Uint8Array.from(atob(image), character => character.charCodeAt(0));',
    '  return [bytes.slice(0, 1024), bytes.slice(1024)];',
    '}',
    ''
  ].join('\n');
  if (check) {
    if (readFileSync(generatedPath, 'utf8') !== generated) throw new Error('KIM-1 ROM is stale.');
  } else if (binaryOutput) {
    mkdirSync(binaryOutput, {recursive: true});
    writeFileSync(join(binaryOutput, 'brickwright-kim1.bin'), bytes);
    writeFileSync(join(binaryOutput, 'brickwright-6530-003.bin'), bytes.subarray(0, 1024));
    writeFileSync(join(binaryOutput, 'brickwright-6530-002.bin'), bytes.subarray(1024));
  } else {
    writeFileSync(generatedPath, generated);
  }
  console.log(`Brickwright KIM-1 ROM: ${sha256}`);
} finally {
  rmSync(temp, {force: true, recursive: true});
}
