// Regenerate debugger metadata from the independently authored monitor build.
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';

const [buildDir] = process.argv.slice(2);
if (!buildDir) throw new Error('Usage: node scripts/generate-cp1-monitor-profile.mjs build/cp1');
const rom = readFileSync(join(buildDir, 'cp1-monitor.bin'));
assert.equal(rom.length, 2048);
const symbols = JSON.parse(readFileSync(join(buildDir, 'cp1-monitor.symbols.json'), 'utf8'));
assert.equal(createHash('sha1').update(rom).digest('hex'), symbols.rom_sha1);

const {display, comparison} = symbols;
assert.equal(display.length, 6);
assert.equal(display.segment_mask, 0x7f);
const identity = {
  id: 'cp1-independent-monitor-v1',
  name: 'Brickwright CP1 independent monitor',
  bytes: rom.length,
  sha1: symbols.rom_sha1,
};
const geometry = {
  version: 1,
  id: identity.id,
  romSha1: identity.sha1,
  evidence: 'docs/CP1-INDEPENDENT-MONITOR.md',
  registers: {
    pc: symbols.teaching_pc,
    accumulator: {opcode: symbols.accumulator_high, operand: symbols.accumulator_low},
    comparison: {...comparison, label: 'Comparison condition is true'},
  },
  commandBoundary: symbols.pre_command,
  monitorBoundary: symbols.monitor_idle,
  haltOpcodes: [1],
  errorDisplay: {
    indicatorAddress: display.address,
    indicatorValue: 0x71,
    digitAddresses: [3, 4, 5].map(offset => display.address + offset),
    digitMasks: [0x3f, 0x06, 0x5b, 0x4f, 0x66, 0x6d, 0x7d, 0x27, 0x7f, 0x6f],
  },
};
writeFileSync(new URL('../src/cp1-monitor-profile.generated.js', import.meta.url), [
  '// SPDX-License-Identifier: MIT',
  '// Generated by scripts/generate-cp1-monitor-profile.mjs from the independent firmware build.',
  `export const CP1_INDEPENDENT_MONITOR_ROM = Object.freeze(${JSON.stringify(identity, null, 2)});`,
  `export const CP1_INDEPENDENT_MONITOR_SEMANTICS = ${JSON.stringify(geometry, null, 2)};`,
  '',
].join('\n'));
