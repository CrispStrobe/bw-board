/** Owned boot program, documented byte-for-byte; no archival firmware. */
export function createHarrisBootROM() {
    const rom = new Uint8Array(65536).fill(0xff); // unsupported bytes catch escapes
    rom.set([0xea, 0x00, 0x01, 0x00, 0xf0], 0xfff0); // JMP FAR F000:0100
    rom.set([
        0xfa,                         // CLI
        0xb8, 0x34, 0x12,             // MOV AX,1234h
        0xa3, 0x00, 0x05,             // MOV [0500h],AX
        0xb8, 0x78, 0x56,             // MOV AX,5678h
        0xa3, 0x02, 0x05,             // MOV [0502h],AX
        0xa1, 0x00, 0x05,             // MOV AX,[0500h]
        0x03, 0x06, 0x02, 0x05,       // ADD AX,[0502h]
        0xa3, 0x04, 0x05,             // MOV [0504h],AX
        0xf4                          // HLT
    ], 0x100);
    return rom;
}

/** Matches test/fixtures/harris-boot/loop.asm; assembler-checked in tests. */
export function createHarrisLoopROM() {
    const rom = createHarrisBootROM();
    rom.fill(255, 0x100, 0xfff0);
    rom.set([
        0xbb, 0x00, 0x05, 0xb9, 0x04, 0x00, 0xb8, 0x01, 0x00,
        0x89, 0x07, 0x40, 0x43, 0x43, 0xe2, 0xf9,
        0xbb, 0x00, 0x05, 0xb9, 0x04, 0x00, 0xb8, 0x00, 0x00,
        0x03, 0x07, 0x43, 0x43, 0xe2, 0xfa,
        0x3d, 0x0a, 0x00, 0x75, 0x04, 0xa3, 0x10, 0x05, 0xf4,
        0xb8, 0xad, 0xde, 0xa3, 0x10, 0x05, 0xf4
    ], 0x100);
    return rom;
}
